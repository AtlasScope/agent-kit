def main():
    for src, dst in COPIES.items():
        shutil.copyfile(os.path.join(ROOT, src), os.path.join(SITE, dst))
    with open(os.path.join(SITE, "app/opengraph-image.alt.txt"), "w") as fh:
        fh.write("Agent Kit by AtlasScope\n")
    # header logo: the lockup for wide screens, the symbol alone for narrow ones
    full_w, mark_w, word, syms = header_logo()
    sym_paths = "\n".join(f'        <path className="aslogo__sym aslogo__sym--{k}" d="{d}" />' for k, d in syms)
    tsx = f'''// Generated by design/atlasscope/source/export_site.py. Do not edit by hand; change the design source and re-run.
// The lettering is outlines, so it does not depend on a font.
//
// This drawing is fitted to the pixel grid for the header only. One unit is one CSS pixel. The box is
// {HDR_H} tall; capitals run from y = {HDR_TOP} to the baseline at y = {HDR_BASE} ({HDR_CAP} px), lowercase tops sit at
// y = {HDR_BASE - HDR_XH}, and the band starts {n(HDR_GAP["x1"])} px under the feet and is {HDR_BAND} px thick. Those rows are whole device
// pixels at 100%, 150% and 200%. At 125% a 2 px gap would be 2.5 device pixels, so a second symbol with
// a 2.4 px gap (3 device pixels) is swapped in by CSS. Keep the svg at its own width and height, with no
// scaling or transform, and keep its top edge on a multiple of 4 px.
export function AtlasScopeLogo() {{
  return (
    <>
      <svg className="aslogo aslogo--full" width="{full_w}" height="{HDR_H}" viewBox="0 0 {full_w} {HDR_H}" fill="currentColor" aria-hidden="true">
{sym_paths}
        <path d="{word}" />
      </svg>
      <svg className="aslogo aslogo--mark" width="{mark_w}" height="{HDR_H}" viewBox="0 0 {mark_w} {HDR_H}" fill="currentColor" aria-hidden="true">
{sym_paths}
      </svg>
    </>
  );
}}
'''
    with open(os.path.join(SITE, "components/AtlasScopeLogo.tsx"), "w") as fh:
        fh.write(tsx)
    print("header lockup", full_w, "x", HDR_H, "symbol", mark_w, "x", HDR_H)


# ---- Header logo, fitted to the pixel grid ---------------------------------------------------
# Sizes in CSS pixels. With the box top on a multiple of 4 px, every row below is a whole device
# pixel at 100%, 125%, 150% and 200% scaling.
HDR_H = 32            # box height
HDR_TOP = 4           # top of the capitals
HDR_CAP = 16          # cap height: 20 device px at 125%, 24 at 150%
HDR_BASE = HDR_TOP + HDR_CAP
HDR_XH = 12           # lowercase height, moved from 12.2 so flat tops land on a row
HDR_BAND = 4          # band thickness
HDR_GAP = {"x1": 2.0, "x125": 2.4}   # feet to band; 2.4 px is 3 device px at 125%
XH_UNITS = 534.0      # flat top of the x in letter units


def fit_y(u):
    """Height above the baseline in letter units -> px. Baseline, lowercase tops and cap tops land on whole px."""
    s = HDR_CAP / G.CAP
    if u <= 0:
        return u * s
    if u <= XH_UNITS:
        return u * HDR_XH / XH_UNITS
    if u <= G.CAP:
        return HDR_XH + (u - XH_UNITS) * (HDR_CAP - HDR_XH) / (G.CAP - XH_UNITS)
    return HDR_CAP + (u - G.CAP) * s


def n(v):
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return "0" if s == "-0" else s


def fit_path(d, x0):
    """Re-plot a path drawn at scale 1 from the baseline origin into header pixels."""
    import re
    s = HDR_CAP / G.CAP
    toks = re.findall(r"[MLHVQCZ]|-?\d+(?:\.\d+)?", d)
    out, i, cx, cy = [], 0, 0.0, 0.0
    P = lambda x, y: f"{n(x0 + x * s)} {n(HDR_BASE - fit_y(-y))}"
    while i < len(toks):
        c = toks[i]; i += 1
        if c == "Z":
            out.append("Z"); continue
        k = {"M": 2, "L": 2, "H": 1, "V": 1, "Q": 4, "C": 6}[c]
        while i < len(toks) and toks[i] not in "MLHVQCZ":
            v = [float(q) for q in toks[i:i + k]]; i += k
            if c == "H":
                cx = v[0]; out.append("L" + P(cx, cy))
            elif c == "V":
                cy = v[0]; out.append("L" + P(cx, cy))
            else:
                out.append(c + " ".join(P(v[j], v[j + 1]) for j in range(0, k, 2)))
                cx, cy = v[-2], v[-1]
    return "".join(out)


def header_logo():
    """Returns (lockup width, symbol width, wordmark path, [(variant, symbol path)])."""
    u = HDR_CAP / G.S_H                      # px per symbol unit: the symbol's A is as tall as the capitals
    syms, right = [], 0.0
    for key, gap in HDR_GAP.items():
        kw = dict(stroke=G.SMALL["stroke"], band=HDR_BAND / u, gap=gap / u, over=G.SMALL["over"])
        m = G.symbol_metrics(**kw)
        x0 = -G.symbol_metrics(**dict(kw, gap=HDR_GAP["x1"] / u))["left"] * u    # same apex position in every variant
        d, _ = G.symbol_path(x0, HDR_BASE, u, **kw)
        assert HDR_BASE - m["bottom"] * u <= HDR_H, "symbol does not fit the header box"
        syms.append((key, d))
        if key == "x1":
            right = (m["right"] - m["left"]) * u
    import math
    raw, ww = G.wordmark_path(0, 0, 1)
    wx = right + B.LOCK_GAP * HDR_CAP / G.CAP
    word = fit_path(raw, wx)
    return math.ceil(wx + ww * HDR_CAP / G.CAP), math.ceil(right), word, syms


if __name__ == "__main__":
    main()
