"""Copies the AtlasScope logo into the site: icons, share image and the header logo component.

Run after build.py:  python3 design/atlasscope/source/export_site.py
"""
import os, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SITE = os.path.join(os.path.dirname(os.path.dirname(ROOT)), "site")
sys.path.insert(0, HERE)
import geometry as G
import build as B

COPIES = {
    "icons/favicon.svg": "app/icon.svg",
    "icons/favicon.ico": "app/favicon.ico",
    "icons/apple-touch-icon.png": "app/apple-icon.png",
    "social/og-agent-kit-1200x630.png": "app/opengraph-image.png",
}


def main():
    for src, dst in COPIES.items():
        shutil.copyfile(os.path.join(ROOT, src), os.path.join(SITE, dst))
    with open(os.path.join(SITE, "app/opengraph-image.alt.txt"), "w") as fh:
        fh.write("Agent Kit by AtlasScope\n")
    # header logo: the lockup for wide screens, the symbol alone for narrow ones
    _, lw, lh = B.lockup(0, 0, 1, "currentColor")
    m, sw, sh = B.sym_box()
    sym, _ = G.symbol_path(-m["left"], m["top"], 1)
    sd, _ = B.symbol_at(0, B.ASC - G.CAP, sw * B.LOCK_S)
    wd, _ = G.wordmark_path(sw * B.LOCK_S + B.LOCK_GAP, B.ASC, 1)
    f = G.f
    tsx = f'''// Generated by design/atlasscope/source/export_site.py. Do not edit by hand; change the design source and re-run.
// The lettering is outlines, so it does not depend on a font. Sizes are in em: 1em = the header wordmark's font size.

// Lockup: box {f(lw)} x {f(lh)}, cap height {f(G.CAP)}. Symbol: box {f(sw)} x {f(sh)}, A height {f(G.S_H)}.
export function AtlasScopeLogo() {{
  return (
    <>
      <svg className="aslogo aslogo--full" viewBox="0 0 {f(lw)} {f(lh)}" fill="currentColor" aria-hidden="true">
        <path d="{sd}" />
        <path d="{wd}" />
      </svg>
      <svg className="aslogo aslogo--mark" viewBox="0 0 {f(sw)} {f(sh)}" fill="currentColor" aria-hidden="true">
        <path d="{sym}" />
      </svg>
    </>
  );
}}
'''
    with open(os.path.join(SITE, "components/AtlasScopeLogo.tsx"), "w") as fh:
        fh.write(tsx)
    print("lockup", round(lw), round(lh), "symbol", round(sw, 1), round(sh, 1))


if __name__ == "__main__":
    main()
