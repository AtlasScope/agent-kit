test("the tokenizer keeps strings, templates and regexes apart and survives JSX text", () => {
  const toks = tokenize('const a = "x/y"; const r = /a"b/g; const d = a / 2 / 3;\nconst t = `p ${q} r`;\n<p>Don\'t</p>;\nconst after = "z";');
  const strs = toks.filter((t) => t.t === "str").map((t) => t.v);
  assert.deepEqual(strs, ["x/y", "z"]);
  assert.equal(toks.filter((t) => t.t === "re").length, 1);
  assert.equal(toks.find((t) => t.t === "tpl").v, "p ${} r");
  assert.equal(toks.find((t) => t.v === "after").line, 4);
});

test("imports: named, aliased, type-only, re-export, dynamic and require", () => {
  const im = importsOf(tokenize('import a, { b as c, type d } from "./x";\nimport type { T } from "./t";\nexport * from "./y";\nconst m = await import("./z");\nconst r = require("./w");\nimport.meta.url;'));
  assert.deepEqual(im.map((x) => [x.spec, x.how]), [["./x", "static import"], ["./t", "type-only import"], ["./y", "re-export"], ["./z", "dynamic import"], ["./w", "require"]]);
  assert.deepEqual(im[0].names.map((n) => `${n.imported}>${n.local}`), ["default>a", "b>c", "d>d"]);
});

test("relationships stay distinct, with anchors, and reading the repository changes nothing", (t) => {
  const dir = fixture(FILES);
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const before = git(dir, "status", "--porcelain");
  const g = buildGraph(dir);
  const has = (kind, from, to) => g.edges.find((e) => e.kind === kind && e.from === from && e.to === to);
  // imports through a tsconfig alias (with comments and a trailing comma), relative and type-only
  assert.ok(has("import", "app/lib/content.ts", "app/page.tsx"));
  assert.equal(has("import", "app/lib/copy.ts", "app/lib/content.ts").line, 2);
  assert.equal(has("import", "app/lib/types.ts", "app/lib/content.ts").basis, "type-only import");
  // a generated, ignored file keeps its place in the chain: build.mjs writes it, content.ts imports it
  assert.ok(has("import", "app/content/generated.json", "app/lib/content.ts"));
  assert.equal(has("generates", "app/scripts/build.mjs", "app/content/generated.json").line, 11);
  // a read through a wrapper, and copyFileSync's source is read while its destination is written
  assert.match(has("reads", "library/data.json", "app/scripts/build.mjs").basis, /read\(\) wraps a read|copyFileSync/);
  assert.ok(has("generates", "app/scripts/build.mjs", "app/content/copy.json"));
  assert.ok(!has("generates", "app/scripts/build.mjs", "library/data.json"));
  // reads by new URL(..., import.meta.url); a child process through a wrapper; package.json, CI and a doc
  assert.ok(has("reads", "library/template.html", "library/build.mjs"));
  assert.ok(has("runs", "app/scripts/build.mjs", "library/build.mjs"));
  assert.equal(has("runs", "app/scripts/build.mjs", "app/package.json").basis, "package.json script");
  assert.equal(has("runs", "library/build.mjs", ".github/workflows/ci.yml").basis, "CI or config step");
  assert.equal(has("mentions", "library/build.mjs", "README.md").basis, "documented command");
  assert.equal(has("generates", "library/build.mjs", "docs/generated.md").basis, "named in the file's generated header");
  // side effects: the git commit is named as one that changes the repository
  assert.ok(g.effects.get("library/build.mjs").some((x) => x.kind === "git" && /changes the repository/.test(x.detail)));
  assert.equal(git(dir, "status", "--porcelain"), before);
});

test("a symbol: who uses it, where, what else defines it, and who repeats its text", (t) => {
  const dir = fixture(FILES);
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const g = buildGraph(dir);
  const q = query(g, ["app/lib/copy.ts"], { symbol: "compose" });
  const content = q.consumers.find((e) => e.to === "app/lib/content.ts");
  assert.deepEqual(content.uses, [4]); // the aliased name on line 4, not the import line
  assert.ok(q.consumers.some((e) => e.to === "app/scripts/build.mjs"));
  assert.ok(q.inferred.some((e) => e.kind === "same-name" && e.to === "library/template.html"));
  const file = query(g, ["app/lib/copy.ts"]);
  assert.ok(file.inferred.some((e) => e.kind === "shared-text" && e.to === "library/template.html" && e.line === 2));
  // reach follows imports and generation, not mentions
  const down = new Set(file.reach.down.map((r) => r.path));
  assert.ok(down.has("app/page.tsx") && down.has("app/content/generated.json"));
  assert.ok(!down.has("README.md"));
  // co-change helpers: build.mjs and the template are related; data.json is another input of build.mjs
  const rel = relations(g, ["library/template.html"]);
  assert.equal(rel.get("library/build.mjs").relation, "downstream");
  const sib = relations(g, ["app/lib/copy.ts"]).get("library/data.json");
  assert.equal(sib.relation, "sibling");
});

test("the report's evidence names observations by id and every subject it uses", (t) => {
  const dir = fixture(FILES);
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const g = buildGraph(dir);
  const r = report(g, query(g, ["library/build.mjs"]));
  assert.equal(r.evidence.scope, "repository-snapshot");
  const keys = new Set(r.evidence.subjects.map((s) => s.key));
  for (const o of r.evidence.observations) for (const s of o.subjects) assert.ok(keys.has(s), s);
  assert.ok(r.consumers.every((c) => /^o\d+$/.test(c.id)));
  assert.throws(() => query(g, ["missing.js"]), /not a tracked file/);
});
