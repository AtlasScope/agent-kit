// Makes the homepage hero images from the 4k source, which stays out of git.
// Run from site/:  node scripts/build-hero-images.mjs
// Source: ../design/hero/inputs/atlasscope-orbit-hero-4k.png (3840 x 2160)
import sharp from "sharp";
import { mkdir, writeFile, stat } from "node:fs/promises";

const SRC = new URL("../../design/hero/inputs/atlasscope-orbit-hero-4k.png", import.meta.url).pathname;
const OUT = new URL("../public/hero/", import.meta.url).pathname;
await mkdir(OUT, { recursive: true });

const WIDE = [960, 1440, 1920, 2560, 3840];
// Phones get the middle of the frame, kept to the bottom where the horizon is: 4:5.
const TALL = [780, 1170];
const tall = () => sharp(SRC).extract({ left: 1056, top: 0, width: 1728, height: 2160 });

const jobs = [];
for (const w of WIDE) {
  jobs.push([`orbit-${w}.avif`, sharp(SRC).resize({ width: w }).avif({ quality: 50, effort: 6 })]);
  jobs.push([`orbit-${w}.webp`, sharp(SRC).resize({ width: w }).webp({ quality: 72, effort: 6 })]);
}
for (const w of TALL) {
  jobs.push([`orbit-tall-${w}.avif`, tall().resize({ width: w }).avif({ quality: 50, effort: 6 })]);
  jobs.push([`orbit-tall-${w}.webp`, tall().resize({ width: w }).webp({ quality: 72, effort: 6 })]);
}
for (const [name, img] of jobs) {
  await img.toFile(OUT + name);
  console.log(name, Math.round((await stat(OUT + name)).size / 1024) + " KB");
}
// A 24px blurred placeholder, inlined in the CSS so the horizon is there before the photo loads.
const blur = await sharp(SRC).resize({ width: 24 }).blur(1).webp({ quality: 40 }).toBuffer();
await writeFile(new URL("../lib/hero-blur.ts", import.meta.url).pathname,
  `// Generated by scripts/build-hero-images.mjs. Do not edit by hand.\nexport const HERO_BLUR = "data:image/webp;base64,${blur.toString("base64")}";\n`);
console.log("placeholder", blur.length, "bytes");
