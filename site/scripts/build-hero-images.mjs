#!/usr/bin/env node
// Makes the homepage's still images from the scene itself: the code the page runs (components/orbit), drawn at rest
// in a headless browser and saved. Nothing here comes from a photograph. Run it again after changing the look.
//   cd site && node scripts/build-hero-images.mjs
// The stills are what the page shows first, what it shows with reduced motion, and what it falls back to when the
// browser cannot draw the scene. They must match the live scene's framing, so they are drawn on the two reference
// frames in components/orbit/params.ts: 1920 x 1080 for wide screens, 1080 x 1350 for phones, each at twice that.
import { mkdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import { launch, openLab, site, startLab } from "./orbit-browser.mjs";

const OUT = path.join(site, "public", "hero");
const WIDE = [960, 1440, 1920, 2560, 3840], TALL = [780, 1170];

async function draw(browser, base, frame, width, height) {
  // No film grain in the stills: it is noise to the encoders, and the live scene adds its own.
  const page = await openLab(browser, base, { width, height, scale: 2, query: { tier: "still", frame, still: "1" }, look: { grain: 0 } });
  await page.waitForTimeout(1500);
  const info = await page.evaluate(() => window.lab.orbit.stats());
  if (info.width !== width * 2 || info.height !== height * 2) throw new Error(`${frame}: drew ${info.width} x ${info.height}, wanted ${width * 2} x ${height * 2}`);
  const png = await page.screenshot({ type: "png" });
  await page.close();
  return png;
}

await mkdir(OUT, { recursive: true });
const lab = await startLab();
const browser = await launch();
let wide, tall;
try {
  wide = await draw(browser, lab.base, "wide", 1920, 1080);
  tall = await draw(browser, lab.base, "tall", 1080, 1350);
} finally {
  await browser.close();
  lab.stop();
}

const jobs = [];
for (const w of WIDE) {
  jobs.push([`orbit-${w}.avif`, sharp(wide).resize({ width: w }).avif({ quality: 52, effort: 6 })]);
  jobs.push([`orbit-${w}.webp`, sharp(wide).resize({ width: w }).webp({ quality: 74, effort: 6 })]);
}
for (const w of TALL) {
  jobs.push([`orbit-tall-${w}.avif`, sharp(tall).resize({ width: w }).avif({ quality: 52, effort: 6 })]);
  jobs.push([`orbit-tall-${w}.webp`, sharp(tall).resize({ width: w }).webp({ quality: 74, effort: 6 })]);
}
for (const [name, image] of jobs) {
  await image.toFile(path.join(OUT, name));
  console.log(name, Math.round((await stat(path.join(OUT, name))).size / 1024) + " KB");
}
// A 24px blurred placeholder, inlined in the page so the horizon is there before the still loads.
const blur = await sharp(wide).resize({ width: 24 }).blur(1).webp({ quality: 40 }).toBuffer();
await writeFile(path.join(site, "lib", "hero-blur.ts"),
  `// Generated by scripts/build-hero-images.mjs. Do not edit by hand.\nexport const HERO_BLUR = "data:image/webp;base64,${blur.toString("base64")}";\n`);
console.log("placeholder", blur.length, "bytes");
